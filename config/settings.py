# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
# PostgreSQL: set DATABASE_URL or SUPABASE_URL (e.g. from Supabase → Project Settings → Database → Connection string).
# Use the "URI" format; for Supabase prefer the pooler (port 6543) for serverless/Vercel.
# DigitalOcean automatically sets DATABASE_URL when you add a database component to your app.
_db_url = (
    os.environ.get("DATABASE_URL", "").strip()
    or os.environ.get("SUPABASE_URL", "").strip()
    or os.environ.get("SUPABASE_DATABASE_URL", "").strip()
    or os.environ.get("POSTGRES_URL", "").strip()  # Some platforms use this
    or os.environ.get("POSTGRESQL_URL", "").strip()  # Alternative name
)
if _db_url and (_db_url.startswith("postgres://") or _db_url.startswith("postgresql://")):
    from urllib.parse import urlparse, unquote
    try:
        # Ensure SSL is included for DigitalOcean (they require it)
        # DigitalOcean auto-set DATABASE_URL might not include sslmode
        if "sslmode=" not in _db_url:
            separator = "?" if "?" not in _db_url else "&"
            _db_url = f"{_db_url}{separator}sslmode=require"
        
        _parsed = urlparse(_db_url)
        _db_user = _parsed.username
        _db_pass = unquote(_parsed.password) if _parsed.password else None  # URL decode password
        _db_host = _parsed.hostname or "localhost"
        _db_port = _parsed.port or 5432
        _db_name = (_parsed.path or "/").lstrip("/") or "postgres"
        _is_supabase = _db_host and ("supabase.com" in _db_host or "supabase.co" in _db_host)
        # Detect DigitalOcean databases - check for common DigitalOcean host patterns
        _is_digitalocean = _db_host and (
            "digitalocean.com" in _db_host or 
            "db.ondigitalocean.com" in _db_host or 
            "ondigitalocean.com" in _db_host or
            _db_port == 25060  # DigitalOcean's standard port
        )
        
        # Build database config
        db_config = {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": _db_name,
            "USER": _db_user,
            "PASSWORD": _db_pass,
            "HOST": _db_host,
            "PORT": str(_db_port),
            "CONN_MAX_AGE": 600,
        }
        
        # Add SSL for Supabase, DigitalOcean, or if specified in connection string
        if _is_supabase:
            db_config["OPTIONS"] = {"sslmode": "require"}
        elif _is_digitalocean:
            # DigitalOcean managed databases require SSL
            db_config["OPTIONS"] = {"sslmode": "require"}
        elif "sslmode" in _parsed.query:
            # Parse sslmode from query string if present
            from urllib.parse import parse_qs
            query_params = parse_qs(_parsed.query)
            if "sslmode" in query_params:
                db_config["OPTIONS"] = {"sslmode": query_params["sslmode"][0]}
        else:
            # For other cloud providers, try requiring SSL (most need it)
            # User can override with ?sslmode=disable if needed
            db_config["OPTIONS"] = {"sslmode": "require"}
        
        DATABASES = {"default": db_config}
        
        # Log successful database config (without sensitive info)
        import logging
        logger = logging.getLogger(__name__)
        logger.info(f"Configured PostgreSQL database: {_db_host}:{_db_port}/{_db_name}")
        if _is_digitalocean:
            logger.info("DigitalOcean database detected - SSL enabled automatically")
        
    except Exception as e:
        # If parsing fails, log error but continue (will fall back to SQLite with warning)
        import logging
        import traceback
        logger = logging.getLogger(__name__)
        logger.error(f"Error parsing DATABASE_URL: {e}")
        logger.error(traceback.format_exc())
        # Will fall through to SQLite configuration below
        _db_url = None  # Force SQLite fallback
else:
    # SQLite fallback - ONLY for local development
    # WARNING: SQLite is NOT persistent on cloud platforms (Vercel, Railway, Render, etc.)
    # Data will be LOST on each deployment if using SQLite in production!
    # You MUST set DATABASE_URL to a PostgreSQL connection string in production.
    import logging
    logger = logging.getLogger(__name__)
    
    # Check if we're in a production-like environment
    is_production_like = (
        os.environ.get("VERCEL", "").lower() == "true" or
        os.environ.get("RAILWAY_ENVIRONMENT", "") or
        os.environ.get("RENDER", "").lower() == "true" or
        os.environ.get("DYNO", "") or  # Heroku
        not DEBUG
    )
    
    if is_production_like:
        logger.error(
            "⚠️ CRITICAL: Using SQLite in production-like environment! "
            "Data will be LOST on each deployment. "
            "Set DATABASE_URL environment variable to a PostgreSQL connection string. "
            "See docs/DATABASE_PERSISTENCE.md for setup instructions."
        )
    
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


